"""Early completion and authenticated transcription for practice interviews."""

from fastapi.testclient import TestClient

from tests.conftest import Env
from tests.test_answers import answer
from tests.test_recordings import upload_chunk


def complete(client: TestClient, headers: dict, interview_id: str):
    return client.post(f"/api/interviews/{interview_id}/complete", headers=headers)


def test_early_completion_scores_answers_given(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=5)
    first = answer(client, auth_headers, ctx["question_id"])
    assert first.status_code == 200
    assert first.json()["status"] == "in_progress"

    response = complete(client, auth_headers, ctx["id"])
    assert response.status_code == 200, response.text
    body = response.json()
    assert body["status"] == "completed"
    assert body["completed_at"] is not None
    assert len(body["answers"]) == 1
    # No next question was generated by completion.
    assert len(body["questions"]) == 2

    report = client.get(f"/api/interviews/{ctx['id']}/report", headers=auth_headers)
    assert report.status_code == 200, report.text
    assert report.json()["overall_score"] == 80.0


def test_early_completion_requires_at_least_one_answer(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=3)
    response = complete(client, auth_headers, ctx["id"])
    assert response.status_code == 409
    assert "at least one question" in response.json()["detail"]


def test_early_completion_is_idempotent(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=3)
    assert answer(client, auth_headers, ctx["question_id"]).status_code == 200

    first = complete(client, auth_headers, ctx["id"])
    assert first.status_code == 200
    second = complete(client, auth_headers, ctx["id"])
    assert second.status_code == 200
    assert second.json()["status"] == "completed"


def test_early_completion_of_another_users_interview_is_404(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=2)
    assert answer(client, auth_headers, ctx["question_id"]).status_code == 200

    email = "other.complete@example.com"
    assert (
        client.post(
            "/api/auth/register",
            json={"name": "Other", "email": email, "password": "strongpassword1"},
        ).status_code
        == 201
    )
    login = client.post(
        "/api/auth/login", json={"email": email, "password": "strongpassword1"}
    )
    other = {"Authorization": f"Bearer {login.json()['access_token']}"}
    assert complete(client, other, ctx["id"]).status_code == 404


def test_recording_can_finalize_after_early_completion(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=3)
    assert upload_chunk(client, auth_headers, ctx["id"], seq=0, blob=b"first").status_code == 204
    assert answer(client, auth_headers, ctx["question_id"]).status_code == 200
    assert complete(client, auth_headers, ctx["id"]).status_code == 200

    assert (
        upload_chunk(
            client, auth_headers, ctx["id"], seq=1, finalize=True, blob=b"tail"
        ).status_code
        == 204
    )
    download = client.get(
        f"/api/interviews/{ctx['id']}/recordings/camera", headers=auth_headers
    )
    assert download.status_code == 200
    assert download.content == b"firsttail"

    # A completed recording cannot be restarted.
    restart = upload_chunk(client, auth_headers, ctx["id"], seq=0, blob=b"wipe")
    assert restart.status_code == 409


def test_empty_recording_is_not_advertised(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=2)
    response = upload_chunk(
        client, auth_headers, ctx["id"], seq=0, finalize=True, blob=b""
    )
    assert response.status_code == 204
    detail = client.get(f"/api/interviews/{ctx['id']}", headers=auth_headers).json()
    assert "camera" not in detail["recordings"]
    assert (
        client.get(
            f"/api/interviews/{ctx['id']}/recordings/camera", headers=auth_headers
        ).status_code
        == 404
    )


def test_authenticated_transcription_is_501_when_unconfigured(
    client: TestClient, auth_headers: dict, env: Env
) -> None:
    ctx = env.setup(target=2)
    response = client.post(
        f"/api/interviews/{ctx['id']}/transcribe",
        headers=auth_headers,
        data={"content_type": "audio/webm"},
        files={"audio": ("answer.webm", b"fake-audio", "audio/webm")},
    )
    assert response.status_code == 501
